use gpui::SharedString;

/// Built-in aliases for editing defaults when no exact grammar name is registered.
/// Availability of a parser does not change what a language name means.
pub(crate) fn language_name(name: &str) -> SharedString {
    let name = name.to_lowercase();
    match name.as_str() {
        "plain" => "text".into(),
        "plaintext" => "text".into(),
        "jsonc" => "json".into(),
        "sh" => "bash".into(),
        "c++" => "cpp".into(),
        "cs" => "csharp".into(),
        "scss" => "css".into(),
        "ex" => "elixir".into(),
        "js" => "javascript".into(),
        "kt" => "kotlin".into(),
        "kts" => "kotlin".into(),
        "ktm" => "kotlin".into(),
        "makefile" => "make".into(),
        "md" => "markdown".into(),
        "mdx" => "markdown".into(),
        "markdown-inline" => "markdown_inline".into(),
        "php3" => "php".into(),
        "php4" => "php".into(),
        "php5" => "php".into(),
        "phtml" => "php".into(),
        "protobuf" => "proto".into(),
        "py" => "python".into(),
        "rb" => "ruby".into(),
        "rs" => "rust".into(),
        "ts" => "typescript".into(),
        "yml" => "yaml".into(),
        "pyi" => "python".into(),
        "shell" | "zsh" | "ksh" | "console" | "shellsession" | "shell-session" => "bash".into(),
        "h" => "c".into(),
        "cc" | "cxx" | "hpp" | "hh" | "hxx" => "cpp".into(),
        "c#" => "csharp".into(),
        "patch" | "udiff" => "diff".into(),
        "exs" => "elixir".into(),
        "golang" => "go".into(),
        "gql" => "graphql".into(),
        "htm" | "xhtml" => "html".into(),
        "jsx" | "mjs" | "cjs" => "javascript".into(),
        "json5" | "jsonl" => "json".into(),
        "mk" => "make".into(),
        "python3" | "py3" => "python".into(),
        "postgresql" | "postgres" | "pgsql" | "mysql" | "sqlite" => "sql".into(),
        "mts" | "cts" => "typescript".into(),
        "erl" | "hrl" => "erlang".into(),
        "f#" | "fs" | "fsx" | "fsi" => "fsharp".into(),
        "vert" | "frag" | "geom" | "comp" => "glsl".into(),
        "hs" => "haskell".into(),
        "terraform" | "tf" | "tfvars" => "hcl".into(),
        "jl" => "julia".into(),
        "objective-c" | "objectivec" | "obj-c" | "objective_c" => "objc".into(),
        "ml" => "ocaml".into(),
        "pl" | "pm" => "perl".into(),
        "ps1" | "pwsh" | "psm1" | "psd1" | "ps" => "powershell".into(),
        "svg" | "xsd" | "xsl" | "xslt" | "plist" | "rss" | "atom" | "xaml" | "csproj" => {
            "xml".into()
        }
        _ => name.into(),
    }
}
